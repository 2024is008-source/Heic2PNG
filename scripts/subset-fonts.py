"""Optional asset regeneration: fonttools[woff]. Normal builds use committed files.

Common Latin/punctuation/symbol glyphs are smaller, but every original character
remains available through complementary unicode-range full-font fallbacks.
"""
from hashlib import sha256
from io import BytesIO
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

folder = Path('public/fonts')
common = [(0, 0x24F), (0x1E00, 0x1EFF), (0x2000, 0x2BFF), (0xFEFF, 0xFEFF), (0xFFFD, 0xFFFD)]
fallback = [(0x250, 0x1DFF), (0x1F00, 0x1FFF), (0x2C00, 0xFEFE), (0xFF00, 0xFFFC), (0xFFFE, 0x10FFFF)]

def ranges(items):
    return ','.join(f'U+{a:X}-{b:X}' if a != b else f'U+{a:X}' for a, b in items)

css = ['/* Generated by scripts/subset-fonts.py. Original full fonts are retained. */']
for family, stem, weights in [('Inter', 'Inter', [400, 500, 600, 700, 800]), ('JetBrains Mono', 'JetBrains-Mono', [400, 500, 600])]:
    for weight in weights:
        source = folder / f'{stem}-{weight}.woff2'
        original = TTFont(source, recalcTimestamp=False)
        cmap = original.getBestCmap()
        unicodes = {cp for cp in cmap if any(a <= cp <= b for a, b in common)}
        font = TTFont(source, recalcTimestamp=False)
        options = subset.Options()
        options.layout_features = ['*']
        options.recalc_timestamp = False
        processor = subset.Subsetter(options=options)
        processor.populate(unicodes=unicodes)
        processor.subset(font)
        font.flavor = 'woff2'
        output = BytesIO()
        font.save(output)
        data = output.getvalue()
        filename = f'{stem}-{weight}-latin.{sha256(data).hexdigest()[:12]}.woff2'
        (folder / filename).write_bytes(data)
        restored = TTFont(BytesIO(data), recalcTimestamp=False)
        for cp in unicodes:
            assert original['hmtx'][cmap[cp]] == restored['hmtx'][restored.getBestCmap()[cp]], (family, weight, cp)
        assert original['head'].unitsPerEm == restored['head'].unitsPerEm
        for src, coverage in [(source.name, fallback), (filename, common)]:
            css.append(f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{weight};font-display:swap;src:url(/fonts/{src}) format('woff2');unicode-range:{ranges(coverage)};}}")
        print(f'{filename}: {len(data)} bytes; {len(unicodes)} original-character metrics verified')

(folder / 'fonts.css').write_text('\n'.join(css) + '\n', encoding='utf8')
